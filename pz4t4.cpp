#include <iostream>
#include <stack>
#include <cstdlib>  // Для rand() та srand()
#include <ctime>    // Для time()

using namespace std;

int main() {
    stack<int> S;
    const int size = 15; // Максимальна місткість стека (за варіантом B-13)
    int sum = 0; // Змінна для підрахунку суми парних чисел
    int count = 0; // Змінна для підрахунку кількості парних чисел

    srand(time(0)); // Ініціалізація генератора випадкових чисел

    int min = 5;
    int max = 35;

    // Генерація випадкових чисел у діапазоні від 5 до 35
    for (int i = 0; i < size; i++) {
        int randomNum = rand() % (max - min + 1) + min; 
        S.push(randomNum);
    }

    // Виведіть усі числа та обчисліть середнє значення за критерієм
    cout << "Елементи стека (випадкові числа): " << endl;
    while (!S.empty()) 
    {
        int num = S.top(); // Отримати верхній елемент
        S.pop(); // Видалити верхній елемент

        // Вивести число
        cout << num << " ";

        // Перевірка на парність та приналежність до діапазону (10-25)
        if (num >= 10 && num <= 25 && num % 2 == 0)
        {
            sum += num; // Додати до суми
            count++; // Збільшити лічильник парних чисел
        }
    }
    cout << endl; // Перехід на новий рядок після виведення чисел

    // Обчислення та виведення середнього значення парних чисел
    if (count > 0) {
        cout << "Середнє значення парних чисел: " << double(sum) / count << endl;
    } else {
        cout << "Парних чисел не знайдено." << endl;
    }

    return 0;
}